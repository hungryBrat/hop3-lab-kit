def load(path):
    try:
        with open(path) as fh:
            return json.load(fh)
    except FileNotFoundError:
        return None
    except json.JSONDecodeError as e:
        WARN.append(f"bad json {os.path.relpath(path, ROOT)}: {e}")
        return None


UNI = {"θ": r"$\theta$", "°": r"$^\circ$", "±": r"$\pm$", "≥": r"$\geq$", "≤": r"$\leq$",
       "×": r"$\times$", "−": "-", "µ": r"$\mu$", "μ": r"$\mu$", "–": "--", "—": "---",
       "σ": r"$\sigma$", "λ": r"$\lambda$", "≈": r"$\approx$", "²": r"$^2$", "³": r"$^3$",
       "’": "'", "‘": "`", "“": "``", "”": "''", "→": r"$\to$"}


def nonreal(src):
    return src is not None and str(src).upper() != "FITNET"


def tex(s):
    s = str(s)
    out = []
    for ch in s:
        if ch in "\\":
            out.append(r"\textbackslash{}")
        elif ch in "&%$#_{}":
            out.append("\\" + ch)
        elif ch == "~":
            out.append(r"\textasciitilde{}")
        elif ch == "^":
            out.append(r"\textasciicircum{}")
        elif ch in UNI:
            out.append(UNI[ch])
        elif ord(ch) > 127:
            out.append("?")
        else:
            out.append(ch)
    return "".join(out)


class Raw(str):
    pass


def fmt(v, digits=None):
    if v is None:
        return None
    if isinstance(v, Raw):
        return str(v)
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return f"{v:,}".replace(",", r"\,")
    if isinstance(v, float):
        if v != v:
            return None
        if digits is not None:
            return f"{v:.{digits}f}"
        a = abs(v)
        if a == 0:
            return "0"
        if a < 0.01:
            m, e = f"{v:.1e}".split("e")
            return r"\ensuremath{" + m + r"\times10^{" + str(int(e)) + "}}"
        if a < 1:
            return f"{v:.3f}"
        if a < 100:
            return f"{v:.2f}"
        return f"{v:.1f}"
    if isinstance(v, list):
        return "[" + " ".join(fmt(x) or "?" for x in v) + "]"
    return tex(v)


def val(name, v, flag=None, digits=None):
    """LaTeX snippet for value v; flag in {None,'standin','synth'}; records placeholders."""
    s = fmt(v, digits)
    if s is None:
        COUNT["ph"] += 1
        PH_NAMES.append(name)
        return r"\PH{" + tex(name) + "}"
    if flag == "standin":
        COUNT["standin"] += 1
        return r"\FLS{" + s + "}"
    if flag == "synth":
        COUNT["synth"] += 1
        return r"\FLP{" + s + "}"
    return s


def macro(cs, name, v, flag=None, digits=None):
    assert re.fullmatch(r"[A-Za-z]+", cs), cs
    MACROS.append(f"\\newcommand{{\\{cs}}}{{{val(name, v, flag, digits)}}}")


def raw_macro(cs, body):
    MACROS.append(f"\\newcommand{{\\{cs}}}{{{body}}}")


def g(d, *keys):
    for k in keys:
        if d is None:
            return None
        if isinstance(k, int):
            d = d[k] if isinstance(d, list) and len(d) > k else None
        else:
            d = d.get(k) if isinstance(d, dict) else None
    return d


def num(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool) and v == v


def write(name, text):
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% generated by code/python/make_report_numbers.py -- do not edit\n" + text + "\n")


