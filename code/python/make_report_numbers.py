def load(path):
    try:
        with open(path) as fh:
            return json.load(fh)
    except FileNotFoundError:
        return None
    except json.JSONDecodeError as e:
        WARN.append(f"bad json {os.path.relpath(path, ROOT)}: {e}")
        return None


UNI = {"θ": r"$\theta$", "°": r"$^\circ$", "±": r"$\pm$", "≥": r"$\geq$", "≤": r"$\leq$",
       "×": r"$\times$", "−": "-", "µ": r"$\mu$", "μ": r"$\mu$", "–": "--", "—": "---",
       "σ": r"$\sigma$", "λ": r"$\lambda$", "≈": r"$\approx$", "²": r"$^2$", "³": r"$^3$",
       "’": "'", "‘": "`", "“": "``", "”": "''", "→": r"$\to$"}


def nonreal(src):
    return src is not None and str(src).upper() != "FITNET"


def tex(s):
    s = str(s)
    out = []
    for ch in s:
        if ch in "\\":
            out.append(r"\textbackslash{}")
        elif ch in "&%$#_{}":
            out.append("\\" + ch)
        elif ch == "~":
            out.append(r"\textasciitilde{}")
        elif ch == "^":
            out.append(r"\textasciicircum{}")
        elif ch in UNI:
            out.append(UNI[ch])
        elif ord(ch) > 127:
            out.append("?")
        else:
            out.append(ch)
    return "".join(out)


class Raw(str):
    pass


def fmt(v, digits=None):
    if v is None:
        return None
    if isinstance(v, Raw):
        return str(v)
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return f"{v:,}".replace(",", r"\,")
    if isinstance(v, float):
        if v != v:
            return None
        if digits is not None:
            return f"{v:.{digits}f}"
        a = abs(v)
        if a == 0:
            return "0"
        if a < 0.01:
            m, e = f"{v:.1e}".split("e")
            return r"\ensuremath{" + m + r"\times10^{" + str(int(e)) + "}}"
        if a < 1:
            return f"{v:.3f}"
        if a < 100:
            return f"{v:.2f}"
        return f"{v:.1f}"
    if isinstance(v, list):
        return "[" + " ".join(fmt(x) or "?" for x in v) + "]"
    return tex(v)


def val(name, v, flag=None, digits=None):
    """LaTeX snippet for value v; flag in {None,'standin','synth'}; records placeholders."""
    s = fmt(v, digits)
    if s is None:
        COUNT["ph"] += 1
        PH_NAMES.append(name)
        return r"\PH{" + tex(name) + "}"
    if flag == "standin":
        COUNT["standin"] += 1
        return r"\FLS{" + s + "}"
    if flag == "synth":
        COUNT["synth"] += 1
        return r"\FLP{" + s + "}"
    return s


def macro(cs, name, v, flag=None, digits=None):
    assert re.fullmatch(r"[A-Za-z]+", cs), cs
    MACROS.append(f"\\newcommand{{\\{cs}}}{{{val(name, v, flag, digits)}}}")


def raw_macro(cs, body):
    MACROS.append(f"\\newcommand{{\\{cs}}}{{{body}}}")


def g(d, *keys):
    for k in keys:
        if d is None:
            return None
        if isinstance(k, int):
            d = d[k] if isinstance(d, list) and len(d) > k else None
        else:
            d = d.get(k) if isinstance(d, dict) else None
    return d


def write(name, text):
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("% generated by code/python/make_report_numbers.py -- do not edit\n" + text + "\n")


AX = ["X", "Y", "Z"]
JN = ["One", "Two", "Three"]
DIGW = {"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five",
        "6": "six", "7": "seven", "8": "eight", "9": "nine"}


def csname(s):
    s = re.sub(r"\d", lambda m: DIGW[m.group()], s)
    return "".join(p.capitalize() for p in re.split(r"[^A-Za-z]+", s) if p)


def main():
    os.makedirs(OUT, exist_ok=True)
    cfg = load(os.path.join(ROOT, "config.json")) or {}
    sess = load(os.path.join(ROOT, "session", "session_data.json")) or {}
    if SYNTH:
        sess = load(os.path.join(ROOT, "data", "synthetic", "session_data_synth.json")) or sess

    # ---------- dataset ----------
    ds = load(os.path.join(RES, "dataset.json"))
    macro("DataNPoolRaw", "n_pool_raw", g(ds, "n_pool_raw"))
    macro("DataNPoolKept", "n_pool_kept", g(ds, "n_pool_kept"))
    macro("DataNTest", "n_test", g(ds, "n_test"))
    macro("DataNTrajTest", "n_traj_test", g(ds, "n_traj_test"))
    macro("DataZFloor", "z_floor_mm", g(ds, "z_floor_mm"))

    # ---------- fk_eval ----------
    fk = load(os.path.join(RES, "fk_eval.json"))
    fk_standin = nonreal(g(fk, "model_source"))
    ff = "standin" if fk_standin else None
    macro("FKSource", "model_source", g(fk, "model_source"), ff)
    arch = g(fk, "arch")
    macro("FKArch", "arch", Raw(r"\texttt{[" + " ".join(str(x) for x in arch) + "]}") if isinstance(arch, list) else arch, ff)
    macro("FKTrainFcn", "train_fcn", g(fk, "train_fcn"), ff)
    macro("FKNWeights", "n_weights", g(fk, "n_weights"), ff)
    for i, a in enumerate(AX):
        macro(f"FKRMSE{a}", f"rmse_{a.lower()}", g(fk, "rmse_mm", i), ff)
        macro(f"FKMAE{a}", f"mae_{a.lower()}", g(fk, "mae_mm", i), ff)
        r2 = g(fk, "r2", i)
        macro(f"FKRtwo{a}", f"r2_{a.lower()}", r2, ff, digits=8 if isinstance(r2, float) else None)
        m, sd = g(fk, "seeds_rmse_mean_mm", i), g(fk, "seeds_rmse_std_mm", i)
        macro(f"FKSeedRMSE{a}", f"seeds_rmse_{a.lower()}",
              None if m is None or sd is None else Raw(f"{fmt(m)} $\\pm$ {fmt(sd)}"), ff)
        macro(f"FKLinRMSE{a}", f"linear_rmse_{a.lower()}", g(fk, "linear_baseline_rmse_mm", i), ff)
    macro("FKEuclMean", "eucl_mean_mm", g(fk, "eucl_mean_mm"), ff)
    macro("FKEuclMedian", "eucl_median_mm", g(fk, "eucl_median_mm"), ff)
    macro("FKPninetyfive", "eucl_p95_mm", g(fk, "eucl_p95_mm"), ff)
    macro("FKEuclMax", "eucl_max_mm", g(fk, "eucl_max_mm"), ff)
    macro("FKLargestErrRegion", "largest_error_region", g(fk, "largest_error_region"), ff)
    # optional training-record keys (not in CONTRACTS; shown if train_fk.m writes them)
    seeds = load(os.path.join(RES, "fk_seeds.json"))
    if seeds and fk and seeds.get("arch") == fk.get("arch") and seeds.get("train_fcn") == fk.get("train_fcn"):
        b = (seeds.get("chosen_seed") or 1) - 1
        for k in ("best_epoch", "train_time_s"):
            v = seeds.get(k)
            if isinstance(v, list) and len(v) > b and fk.get(k) is None:
                fk[k] = v[b]
    for cs, keys in [("FKEpochs", ("best_epoch", "epochs_reached", "epochs")),
                     ("FKTrainTime", ("train_time_s", "training_time_s")),
                     ("FKMuFinal", ("mu_final", "mu")),
                     ("FKStopReason", ("tr_stop", "stop_reason"))]:
        v = next((g(fk, k) for k in keys if g(fk, k) is not None), None)
        macro(cs, keys[0], v, ff)
    p95 = g(fk, "eucl_p95_mm")
    rm = g(fk, "rmse_mm")
    if p95 is None or rm is None:
        raw_macro("FKTargetVerdict", r"\PH{target verdict}")
        COUNT["ph"] += 1
    else:
        ok = p95 <= 0.5 and max(rm) <= 0.2
        raw_macro("FKTargetVerdict", ("meets" if ok else "does not meet") +
                  (r"\FLS{}" if fk_standin else ""))

    # ---------- trajectories ----------
    trajs = {}
    for p in sorted(glob.glob(os.path.join(RES, "traj_*.json"))):
        d = load(p)
        if d is not None:
            n = d.get("name") or os.path.basename(p)[5:-5]
            if n != "compare_ik":
                trajs[n] = d

    def traj_flag(name):
        meta = load(os.path.join(ROOT, "data", f"cmd_{name}.json")) or {}
        if meta.get("placeholder"):
            return "synth"
        if nonreal(trajs.get(name, {}).get("model_source") or meta.get("model_source")) or fk_standin:
            return "standin"
        return None

    chosen = sess.get("chosen_trajectory")
    if not chosen:
        prim = sorted(n for n in trajs if n.startswith("primary"))
        chosen = next((n for n in prim if trajs[n].get("within_limits")), prim[0] if prim else None)
    sess_flag_traj = None if sess.get("chosen_trajectory") else "synth"
    macro("TrajChosenName", "chosen_trajectory", chosen, sess_flag_traj)
    t = trajs.get(chosen, {}) if chosen else {}
    tf = traj_flag(chosen) if t else None
    macro("TrajPrimaryResid", "inv_residual_rms", g(t, "inv_residual_rms_mm"), tf)
    macro("TrajPrimaryResidMax", "inv_residual_max", g(t, "inv_residual_max_mm"), tf)
    macro("TrajPrimaryDHErr", "dh_err_rms", g(t, "dh_err_rms_mm"), tf)
    macro("TrajPrimaryDHErrMax", "dh_err_max", g(t, "dh_err_max_mm"), tf)
    macro("TrajPrimaryStep", "max_joint_step", g(t, "max_joint_step_deg"), tf)
    for i, j in enumerate(JN):
        macro(f"TrajPrimaryIKDiff{j}", f"q_nn_minus_ik_{i+1}", g(t, "q_nn_minus_ik_rms_deg", i), tf)
    for nm, cs in [("backup", "Backup"), ("outside", "Outside")]:
        d = trajs.get(nm, {})
        macro(f"Traj{cs}DHErr", f"{nm} dh_err_rms", g(d, "dh_err_rms_mm"), traj_flag(nm) if d else None)

    order = sorted(trajs, key=lambda n: (not n.startswith("primary"), not n.startswith("inair"), n))
    rows = []
    for n in order:
        d = trajs[n]
        fl = traj_flag(n)
        ik = g(d, "q_nn_minus_ik_rms_deg")
        cells = [r"\texttt{" + tex(n) + "}" + (r"$^\star$" if n == chosen else ""),
                 val(n + " n", g(d, "n_points")),
                 val(n + " resid", g(d, "inv_residual_rms_mm"), fl),
                 val(n + " resid max", g(d, "inv_residual_max_mm"), fl),
                 val(n + " dh", g(d, "dh_err_rms_mm"), fl),
                 val(n + " dh max", g(d, "dh_err_max_mm"), fl),
                 val(n + " step", g(d, "max_joint_step_deg"), fl),
                 val(n + " ik", Raw("/".join(f"{x:.3f}" for x in ik)) if isinstance(ik, list) else None, fl),
                 val(n + " limits", g(d, "within_limits"), fl)]
        rows.append(" & ".join(cells) + r" \\")
    if not rows:
        rows = [r"\PH{traj\_*.json} & \multicolumn{8}{c}{no trajectory results yet} \\"]
        COUNT["ph"] += 1
    write("tab_traj.tex", "\n".join([
        r"\begin{tabular}{@{}lrrrrrrcc@{}}", r"\toprule",
        r"Trajectory & $N$ & \multicolumn{2}{c}{$\|\mathrm{NN}(q)-p_d\|$ [mm]} & "
        r"\multicolumn{2}{c}{$\|\mathrm{DH}(q)-p_d\|$ [mm]} & max $|\Delta q|$ & "
        r"$q_\mathrm{NN}-q_\mathrm{IK}$ RMS & in limits \\",
        r" & & RMS & max & RMS & max & [deg] & [deg] (J1/J2/J3) & \\", r"\midrule",
        *rows, r"\bottomrule", r"\end{tabular}"]))

    # ---------- sweep ----------
    sw = load(os.path.join(RES, "sweep.json"))
    sf = "standin" if nonreal(g(sw, "model_source")) else None
    sizes, archs = g(sw, "sizes") or [], g(sw, "archs") or []
    for key, fname, title in [("rmse_mean_mm", "tab_sweep_rmse.tex", "test RMSE (mean of axes) [mm]"),
                              ("traj_err_rms_mm", "tab_sweep_traj.tex",
                               r"trajectory error $\|\mathrm{DH}(q_\mathrm{inv})-p_d\|$ RMS [mm]")]:
        if not sizes or not archs:
            write(fname, r"\begin{tabular}{@{}lc@{}}\toprule $N$ & " + title +
                  r" \\\midrule \multicolumn{2}{c}{\PH{sweep.json}} \\\bottomrule\end{tabular}")
            COUNT["ph"] += 1
            continue
        hdr = r"$N$ \textbackslash{} net & " + " & ".join(r"\texttt{" + tex(a) + "}" for a in archs) + r" \\"
        body = []
        for i, n in enumerate(sizes):
            body.append(fmt(n) + " & " + " & ".join(
                val(f"sweep {key} {n} {a}", g(sw, key, i, j), sf) for j, a in enumerate(archs)) + r" \\")
        write(fname, "\n".join([r"\begin{tabular}{@{}l" + "r" * len(archs) + "@{}}", r"\toprule",
                                r"\multicolumn{" + str(len(archs) + 1) + "}{c}{" + title + r"} \\",
                                r"\midrule", hdr, r"\midrule", *body, r"\bottomrule", r"\end{tabular}"]))

    # ---------- outside ----------
    od = load(os.path.join(RES, "outside.json"))
    of = "standin" if fk_standin or nonreal(g(od, "model_source")) else None
    fr = g(od, "frac_outside")
    macro("OutFracPct", "frac_outside", fr * 100 if isinstance(fr, (int, float)) else None, of, digits=0)
    macro("OutErrIn", "err_inside_rms", g(od, "err_inside_rms_mm"), of)
    macro("OutErrOut", "err_outside_rms", g(od, "err_outside_rms_mm"), of)
    ov, oe = g(od, "err_vs_overshoot", "overshoot_deg"), g(od, "err_vs_overshoot", "err_mm")
    macro("OutMaxOvershoot", "max overshoot", max(ov) if ov else None, of, digits=1)
    macro("OutErrAtMaxOvershoot", "err at max overshoot",
          oe[ov.index(max(ov))] if ov and oe and len(oe) == len(ov) else None, of)

    # ---------- run ----------
    runs = {}
    rdirs = [RES] + ([os.path.join(RES, "synthetic")] if SYNTH else [])
    for p in [q for r in rdirs for q in glob.glob(os.path.join(r, "run_*.json"))]:
        d = load(p)
        if d is not None:
            runs[os.path.basename(p)[4:-5]] = (os.path.getmtime(p), d)
    run_name = None
    stems = []
    for e in sess.get("run_logs") or []:
        s = e if isinstance(e, str) else (e.get("file") or e.get("log") or e.get("path") or e.get("name")
                                          if isinstance(e, dict) else None)
        if s:
            st = os.path.splitext(os.path.basename(s))[0]
            stems.append(st[4:] if st.startswith("run_") else st)
    for st in reversed(stems):
        if st in runs:
            run_name = st
            break
        cand = [n for n in runs if n.startswith(st) or st.startswith(n)]
        if cand:
            run_name = max(cand, key=lambda n: runs[n][0])
            break
    if run_name is None and runs:
        pool = [n for n in runs if chosen and chosen in n] or list(runs)
        real = [n for n in pool if not runs[n][1].get("synthetic") and not runs[n][1].get("placeholder")]
        run_name = max(real or pool, key=lambda n: runs[n][0])
    rd = runs[run_name][1] if run_name else None
    rf = "synth" if rd and (rd.get("synthetic") or rd.get("placeholder")) else ("standin" if rd and fk_standin else None)
    macro("RunName", "run name", run_name, rf)
    macro("RunSynthetic", "synthetic", g(rd, "synthetic"))
    terms = [("inv_residual", "InvResid", r"Inversion residual", r"$\mathrm{NN}(q_\mathrm{cmd})-p_\mathrm{des}$",
              "how well the trained net was inverted (solver tolerance)"),
             ("nn_model_err", "NNErr", r"NN model error", r"$\mathrm{DH}(q_\mathrm{cmd})-\mathrm{NN}(q_\mathrm{cmd})$",
              "approximation error of the network on the commanded joints"),
             ("tracking_temporal", "TrackTemp", r"Servo tracking (temporal)",
              r"$\mathrm{DH}(q_\mathrm{meas}(t))-\mathrm{DH}(q_\mathrm{cmd}(t))$", "lag, deadband, load at equal time"),
             ("tracking_contour", "TrackCont", r"Servo tracking (contour)",
              r"nearest-point $\mathrm{DH}(q_\mathrm{meas})\to\mathrm{DH}(q_\mathrm{cmd})$", "path-shape error with lag removed"),
             ("mechanics", "Mech", r"Mechanics / DH vs reality", r"pen $-\ \mathrm{DH}(q_\mathrm{meas})$",
              "backlash, link sag, link-length and zero errors"),
             ("total", "Total", r"\textbf{Total}", r"pen $-\ p_\mathrm{des}$", "end-to-end error on paper")]
    rows = []
    best = None
    for key, cs, label, cmp_, what in terms:
        for stat, sc in [("rms_mm", "RMS"), ("max_mm", "Max"), ("p95_mm", "Pninetyfive")]:
            macro(f"Run{cs}{sc}", f"{key}.{stat}", g(rd, key, stat), rf)
        rows.append(f"{label} & {cmp_} & \\Run{cs}RMS & \\Run{cs}Max & \\Run{cs}Pninetyfive & {what} \\\\")
        v = g(rd, key, "rms_mm")
        if key not in ("total", "tracking_contour") and isinstance(v, (int, float)) and (best is None or v > best[1]):
            best = (label, v)
    write("tab_errors.tex", "\n".join([
        r"\begin{tabular}{@{}llrrrp{4.2cm}@{}}", r"\toprule",
        r"Error source & Comparison & RMS & max & p95 & What it measures \\",
        r" & & [mm] & [mm] & [mm] & \\", r"\midrule", *rows[:-1], r"\midrule", rows[-1],
        r"\bottomrule", r"\end{tabular}"]))
    if best:
        raw_macro("DominantSource", best[0] + (r"\FLP{}" if rf == "synth" else (r"\FLS{}" if rf else "")))
    else:
        raw_macro("DominantSource", r"\PH{dominant source}")
        COUNT["ph"] += 1
    macro("RunLag", "lag_ms", g(rd, "lag_ms"), rf)
    for i, j in enumerate(JN):
        macro(f"RunJointRMS{j}", f"per_joint_rms_{i+1}", g(rd, "per_joint_rms_deg", i), rf)
    macro("RunCircleR", "circle_fit.R_mm", g(rd, "circle_fit", "R_mm"), rf)
    macro("RunCentreErr", "circle_fit.centre_err_mm", g(rd, "circle_fit", "centre_err_mm"), rf)
    macro("RunRErr", "circle_fit.R_err_mm", g(rd, "circle_fit", "R_err_mm"), rf)
    macro("RunHausdorff", "hausdorff_mm", g(rd, "hausdorff_mm"), rf)
    meta = None
    if run_name:
        cand = sorted(glob.glob(os.path.join(ROOT, "logs", f"run_{run_name}*.json")))
        meta = load(cand[-1]) if cand else None
    macro("RunMode", "mode", g(meta, "mode"), rf)

    # ---------- touch-off / trace (keys not fixed by CONTRACTS: tolerant lookup) ----------
    to = load(os.path.join(RES, "touchoff.json"))

    def first(d, *keys):
        return next((d[k] for k in keys if isinstance(d, dict) and d.get(k) is not None), None)
    tflag = "synth" if to and (to.get("placeholder") or to.get("synthetic")) else None
    macro("TouchResidRMS", "touchoff residual", first(to, "residual_rms_mm", "resid_rms_mm", "rms_mm",
                                                      "fit_residual_rms_mm"), tflag)
    macro("TouchPlaneZ", "touchoff plane z", first(to, "plane_z_mm", "paper_plane_z_mm") or g(to, "plane", "z_at_sheet_origin_mm"), tflag)
    macro("TouchTilt", "touchoff tilt", first(to, "plane_tilt_deg", "tilt_deg") or g(to, "plane", "tilt_deg"), tflag)
    traces = sorted(q for r in rdirs for q in glob.glob(os.path.join(r, "trace_*.json")))
    tr = load(traces[-1]) if traces else None
    trf = "synth" if tr and (tr.get("placeholder") or tr.get("synthetic")) else None
    trm = (tr or {}).get("metrics") or tr
    macro("TraceR", "trace R", first(trm, "R_mm", "radius_mm"), trf)
    macro("TraceRErr", "trace R err", first(trm, "R_err_mm"), trf)
    macro("TraceCentreOff", "trace centre offset", first(trm, "centre_offset_mm"), trf)
    macro("TraceRadialRMS", "trace radial rms", first(trm, "radial_rms_vs_fit_mm", "radial_rms_mm"), trf)
    macro("TraceRadialNomRMS", "trace radial rms vs nominal", first(trm, "radial_rms_vs_nominal_mm"), trf)
    macro("TraceHausdorff", "trace hausdorff", first(trm, "hausdorff_vs_nominal_mm", "hausdorff_mm"), trf)
    macro("TraceReproj", "trace homography reproj", first(tr, "reproj_rms_mm"), trf)

    # ---------- session ----------
    def sess_v(cs, key, default=None, digits=None):
        v = sess.get(key)
        if v is None and default is not None:
            macro(cs, key, default, "synth", digits)
        else:
            macro(cs, key, v, None, digits)
    sess_v("SessDate", "date")
    sess_v("SessPort", "port", cfg.get("port"))
    sess_v("SessUSB", "usb_chip_lsusb")
    sess_v("SessPSU", "psu_voltage_V")
    sess_v("SigmaOne", "sigma1", g(cfg, "map", "theta1", "sign"))
    sess_v("SigmaThree", "sigma3", g(cfg, "map", "theta3", "sign"))
    sess_v("NeutralTipHeight", "neutral_tip_height_mm")
    nt = sess.get("neutral_tip_height_mm")
    macro("NeutralTipDiff", "neutral tip diff", nt - 398.6 if isinstance(nt, (int, float)) else None)
    sess_v("PaperPlaneZ", "paper_plane_z_mm")
    sess_v("PenOffset", "pen_offset_mm")
    sess_v("PrintScale", "printed_scale_check_mm")
    sess_v("ZcMM", "z_c_mm")
    sess_v("GripperCmd", "gripper_cmd_deg", cfg.get("gripper_cmd_deg"))
    offs = sess.get("servo_offsets_reg31") or {}
    for k, j in zip("1234", ["One", "Two", "Three", "Four"]):
        macro(f"OffsetReg{j}", f"reg31 id{k}", offs.get(k))
    vid = sess.get("video")
    if vid:
        raw_macro("VideoLink", r"\url{" + str(vid).replace("%", r"\%").replace("#", r"\#") + "}")
    else:
        raw_macro("VideoLink", r"\PH{video link}")
        COUNT["ph"] += 1
