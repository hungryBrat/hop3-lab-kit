def main():
    os.makedirs(OUT, exist_ok=True)
    cfg = load(os.path.join(ROOT, "config.json")) or {}
    sess = load(os.path.join(ROOT, "session", "session_data.json")) or {}
    if SYNTH:
        sess = load(os.path.join(ROOT, "data", "synthetic", "session_data_synth.json")) or {}
    sess_flag = "synth" if SYNTH or sess.get("synthetic") else None
    raw_macro("SynthMode", "1" if SYNTH else "0")

    # ---------- dataset ----------
    ds = load(os.path.join(RES, "dataset.json"))
    macro("DataNPoolRaw", "n_pool_raw", g(ds, "n_pool_raw"))
    macro("DataNPoolKept", "n_pool_kept", g(ds, "n_pool_kept"))
    macro("DataNTest", "n_test", g(ds, "n_test"))
    macro("DataNTrajTest", "n_traj_test", g(ds, "n_traj_test"))
    macro("DataZFloor", "z_floor_mm", g(ds, "z_floor_mm"))

    # ---------- fk_eval ----------
    fk = load(os.path.join(RES, "fk_eval.json"))
    fk_standin = nonreal(g(fk, "model_source"))
    ff = "standin" if fk_standin else None
    macro("FKSource", "model_source", g(fk, "model_source"), ff)
    arch = g(fk, "arch")
    macro("FKArch", "arch", Raw(r"\texttt{[" + " ".join(str(x) for x in arch) + "]}") if isinstance(arch, list) else arch, ff)
    macro("FKTrainFcn", "train_fcn", g(fk, "train_fcn"), ff)
    macro("FKNWeights", "n_weights", g(fk, "n_weights"), ff)
    for i, a in enumerate(AX):
        macro(f"FKRMSE{a}", f"rmse_{a.lower()}", g(fk, "rmse_mm", i), ff)
        macro(f"FKMAE{a}", f"mae_{a.lower()}", g(fk, "mae_mm", i), ff)
        r2 = g(fk, "r2", i)
        macro(f"FKRtwo{a}", f"r2_{a.lower()}", r2, ff, digits=8 if isinstance(r2, float) else None)
        m, sd = g(fk, "seeds_rmse_mean_mm", i), g(fk, "seeds_rmse_std_mm", i)
        macro(f"FKSeedRMSE{a}", f"seeds_rmse_{a.lower()}",
              None if m is None or sd is None else Raw(f"{fmt(m)} $\\pm$ {fmt(sd)}"), ff)
        macro(f"FKLinRMSE{a}", f"linear_rmse_{a.lower()}", g(fk, "linear_baseline_rmse_mm", i), ff)
    macro("FKEuclMean", "eucl_mean_mm", g(fk, "eucl_mean_mm"), ff)
    macro("FKEuclMedian", "eucl_median_mm", g(fk, "eucl_median_mm"), ff)
    macro("FKPninetyfive", "eucl_p95_mm", g(fk, "eucl_p95_mm"), ff)
    macro("FKEuclMax", "eucl_max_mm", g(fk, "eucl_max_mm"), ff)
    macro("FKLargestErrRegion", "largest_error_region", g(fk, "largest_error_region"), ff)
    seeds = load(os.path.join(RES, "fk_seeds.json"))
    if seeds and fk and seeds.get("arch") == fk.get("arch") and seeds.get("train_fcn") == fk.get("train_fcn"):
        b = (seeds.get("chosen_seed") or 1) - 1
        for k in ("best_epoch", "train_time_s"):
            v = seeds.get(k)
            if isinstance(v, list) and len(v) > b and fk.get(k) is None:
                fk[k] = v[b]
    for cs, keys in [("FKEpochs", ("best_epoch", "epochs_reached", "epochs")),
                     ("FKTrainTime", ("train_time_s", "training_time_s")),
                     ("FKMuFinal", ("mu_final", "mu")),
                     ("FKStopReason", ("tr_stop", "stop_reason"))]:
        v = next((g(fk, k) for k in keys if g(fk, k) is not None), None)
        macro(cs, keys[0], v, ff)
    p95 = g(fk, "eucl_p95_mm")
    rm = g(fk, "rmse_mm")
    if p95 is None or rm is None:
        raw_macro("FKTargetVerdict", r"\PH{target verdict}")
        COUNT["ph"] += 1
    else:
        ok = p95 <= 0.5 and max(rm) <= 0.2
        raw_macro("FKTargetVerdict", ("meets" if ok else "does not meet") + (r"\FLS{}" if fk_standin else ""))

    # ---------- letter-B design (config.json: design constants, never flagged) ----------
    trc = cfg.get("trajectories") or {}
    prim_name = cfg.get("primary_trajectory") or "letterB"
    bs = trc.get(prim_name) or {}
    bo = trc.get(prim_name + "_outside") or {}
    rate = g(cfg, "stream", "rate_hz") or 50
    H, zc, yc, xp = bs.get("H"), g(bs, "centre_yz", 1), g(bs, "centre_yz", 0), bs.get("x_plane_mm")
    vmax, dwell = bs.get("v_max_mm_s"), bs.get("corner_dwell_s")
    macro("BxPlane", "letterB x_plane_mm", xp)
    macro("BH", "letterB H", H)
    macro("Bzc", "letterB z_c", zc)
    macro("Byc", "letterB y_c", yc)
    macro("Bvmax", "letterB v_max", vmax)
    macro("Bdwell", "letterB dwell", dwell, digits=1 if num(dwell) else None)
    macro("Brate", "stream rate", rate)
    allnum = all(num(v) for v in (H, zc, yc, vmax))
    macro("BySpine", "spine y", yc - H / 8 if allnum else None, digits=1 if allnum else None)
    macro("BR", "bump radius", H / 4 if allnum else None, digits=1 if allnum else None)
    macro("BzBot", "B bottom z", zc - H / 2 if allnum else None, digits=1 if allnum else None)
    macro("BzTop", "B top z", zc + H / 2 if allnum else None, digits=1 if allnum else None)
    macro("ByMax", "B max y", yc + H / 8 if allnum else None, digits=1 if allnum else None)
    seglen = [H, math.pi * H / 4, math.pi * H / 4] if allnum else [None] * 3
    segT = [math.ceil(1.875 * L / vmax * rate) / rate if allnum else None for L in seglen]
    macro("BLenSpine", "spine length", seglen[0], digits=1 if allnum else None)
    macro("BLenBump", "bump length", seglen[1], digits=1 if allnum else None)
    macro("BTSpine", "spine T", segT[0], digits=2 if allnum else None)
    macro("BTBump", "bump T", segT[1], digits=2 if allnum else None)
    macro("BStepMM", "max path step per tick", 1.875 * seglen[0] / segT[0] / rate if allnum else None, digits=2 if allnum else None)
    macro("BOxPlane", "outside x_plane", bo.get("x_plane_mm"))
    macro("BOyc", "outside y_c", g(bo, "centre_yz", 0))
    macro("BOzc", "outside z_c", g(bo, "centre_yz", 1))
    macro("SafetyMargin", "safety_margin_deg", cfg.get("safety_margin_deg"))
    macro("MaxStepDeg", "max_step_deg", cfg.get("max_step_deg"))
    lim3 = g(cfg, "servo_limits_deg", "j3") or [None, None]
    macro("JThreeLimLo", "j3 limit lo", lim3[0])
    macro("JThreeLimHi", "j3 limit hi", lim3[1])

    # ---------- trajectories ----------
    trajs = {}
    for p in sorted(glob.glob(os.path.join(RES, "traj_*.json"))):
        d = load(p)
        if d is not None:
            n = d.get("name") or os.path.basename(p)[5:-5]
            if n.startswith(prim_name):
                trajs[n] = d

    def traj_flag(name):
        meta = load(os.path.join(ROOT, "data", f"cmd_{name}.json")) or {}
        if meta.get("placeholder") or trajs.get(name, {}).get("placeholder"):
            return "synth"
        if nonreal(trajs.get(name, {}).get("model_source") or meta.get("model_source")) or fk_standin:
            return "standin"
        return None

    chosen = sess.get("chosen_trajectory")
    if chosen not in trajs:
        chosen = prim_name
    t = trajs.get(chosen) or {}
    tf = traj_flag(chosen) if t else None
    macro("TrajChosenName", "chosen_trajectory", chosen)
    macro("TrajPrimaryN", "n_points", g(t, "n_points"), tf)
    T_s = g(t, "T_s")
    if T_s is None and num(g(t, "n_points")):
        T_s = (t["n_points"] - 1) / rate
    macro("TrajPrimaryT", "T_s", T_s, tf, digits=1 if num(T_s) else None)
    macro("TrajPrimaryResid", "inv_residual_rms", g(t, "inv_residual_rms_mm"), tf)
    macro("TrajPrimaryResidMax", "inv_residual_max", g(t, "inv_residual_max_mm"), tf)
    macro("TrajPrimaryDHErr", "dh_err_rms", g(t, "dh_err_rms_mm"), tf)
    macro("TrajPrimaryDHErrMax", "dh_err_max", g(t, "dh_err_max_mm"), tf)
    macro("TrajPrimaryStep", "max_joint_step", g(t, "max_joint_step_deg"), tf)
    macro("TrajPrimaryRowStep", "max_row_step", g(t, "max_row_step_deg"), tf)
    for i, j in enumerate(JN):
        macro(f"TrajPrimaryIKDiff{j}", f"q_nn_minus_ik_{i+1}", g(t, "q_nn_minus_ik_rms_deg", i), tf)
        macro(f"TrajPrimaryThMin{j}", f"theta_min_{i+1}", g(t, "theta_min_deg", i), tf, digits=1)
        macro(f"TrajPrimaryThMax{j}", f"theta_max_{i+1}", g(t, "theta_max_deg", i), tf, digits=1)
    th3 = (g(t, "theta_min_deg", 2), g(t, "theta_max_deg", 2))
    o3 = g(cfg, "map", "theta3", "offset")
    ok3 = num(th3[0]) and num(th3[1]) and num(o3)
    # s3 = o3 + sigma3*theta3 under both possible signs
    macro("SThreeMinusLo", "s3 range sigma=-1 lo", o3 - th3[1] if ok3 else None, tf, digits=1)
    macro("SThreeMinusHi", "s3 range sigma=-1 hi", o3 - th3[0] if ok3 else None, tf, digits=1)
    macro("SThreePlusLo", "s3 range sigma=+1 lo", o3 + th3[0] if ok3 else None, tf, digits=1)
    macro("SThreePlusHi", "s3 range sigma=+1 hi", o3 + th3[1] if ok3 else None, tf, digits=1)
    rob = g(t, "robust_to_signs")
    if isinstance(rob, dict):
        okv = [v for v in rob.values() if isinstance(v, bool)]
        rob = all(okv) if okv else Raw(", ".join(f"{tex(k)}: {fmt(v) or '?'}" for k, v in rob.items()))
    macro("TrajRobust", "robust_to_signs", rob, tf)

    segs = g(t, "segments") or g(load(os.path.join(ROOT, "data", f"cmd_{chosen}.json")), "segments") or []
    if isinstance(segs, dict):
        segs = [segs]
    nominal_len = {"spine": seglen[0], "top": seglen[1], "bottom": seglen[2]}
    srows = []
    for s in segs:
        nm = str(s.get("name", "?"))
        k0, k1 = s.get("k_start"), s.get("k_end")
        dur = (k1 - k0) / rate if num(k0) and num(k1) else None
        L = nominal_len.get(nm)
        srows.append(" & ".join([r"\texttt{" + tex(nm) + "}", val(nm + " k_start", k0, tf), val(nm + " k_end", k1, tf),
                                 val(nm + " duration", dur, tf, digits=2 if num(dur) else None),
                                 val(nm + " length", L, None, digits=1 if num(L) else None),
                                 val(nm + " v peak", 1.875 * L / dur if num(L) and dur else None, tf,
                                     digits=1 if num(L) and dur else None)]) + r" \\")
    if not srows:
        srows = [r"\multicolumn{6}{c}{\PH{segments (traj\_" + tex(chosen) + r".json)}} \\"]
        COUNT["ph"] += 1
    write("tab_segments.tex", "\n".join([
        r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
        r"Segment & $k_\text{start}$ & $k_\text{end}$ & $T_i$ [s] & $L_i$ [mm] & $v_\text{peak}=1.875L_i/T_i$ [mm/s] \\",
        r"\midrule", *srows, r"\bottomrule", r"\end{tabular}"]))

    rows = []
    for n in sorted(trajs, key=lambda n: (n != chosen, n)):
        d = trajs[n]
        fl = traj_flag(n)
        ik = g(d, "q_nn_minus_ik_rms_deg")
        cells = [r"\texttt{" + tex(n) + "}" + (r"$^\star$" if n == chosen else ""),
                 val(n + " n", g(d, "n_points")),
                 val(n + " resid", g(d, "inv_residual_rms_mm"), fl),
                 val(n + " resid max", g(d, "inv_residual_max_mm"), fl),
                 val(n + " dh", g(d, "dh_err_rms_mm"), fl),
                 val(n + " dh max", g(d, "dh_err_max_mm"), fl),
                 val(n + " step", g(d, "max_joint_step_deg"), fl),
                 val(n + " ik", Raw("/".join(f"{x:.3f}" for x in ik)) if isinstance(ik, list) else None, fl),
                 val(n + " limits", g(d, "within_limits"), fl)]
        rows.append(" & ".join(cells) + r" \\")
    if not rows:
        rows = [r"\PH{traj\_" + tex(prim_name) + r"*.json} & \multicolumn{8}{c}{no trajectory results yet} \\"]
        COUNT["ph"] += 1
    write("tab_traj.tex", "\n".join([
        r"\begin{tabular}{@{}lrrrrrrcc@{}}", r"\toprule",
        r"Trajectory & $N$ & \multicolumn{2}{c}{$\|\mathrm{NN}(q)-p_d\|$ [mm]} & "
        r"\multicolumn{2}{c}{$\|\mathrm{DH}(q)-p_d\|$ [mm]} & max $|\Delta q|$ & "
        r"$q_\mathrm{NN}-q_\mathrm{IK}$ RMS & in limits \\",
        r" & & RMS & max & RMS & max & [deg] & [deg] (J1/J2/J3) & \\", r"\midrule",
        *rows, r"\bottomrule", r"\end{tabular}"]))

    # ---------- sweep ----------
    sw = load(os.path.join(RES, "sweep.json"))
    sf = "standin" if nonreal(g(sw, "model_source")) else None
    sizes, archs = g(sw, "sizes") or [], g(sw, "archs") or []
    macro("SweepTrajDef", "sweep traj_def", g(sw, "traj_def"), sf)
    for key, fname, title in [("rmse_mean_mm", "tab_sweep_rmse.tex", "test RMSE (mean of axes) [mm]"),
                              ("traj_err_rms_mm", "tab_sweep_traj.tex",
                               r"trajectory error $\|\mathrm{DH}(q_\mathrm{inv})-p_d\|$ RMS [mm]")]:
        if not sizes or not archs:
            write(fname, r"\begin{tabular}{@{}lc@{}}\toprule $N$ & " + title +
                  r" \\\midrule \multicolumn{2}{c}{\PH{sweep.json}} \\\bottomrule\end{tabular}")
            COUNT["ph"] += 1
            continue
        hdr = r"$N$ \textbackslash{} net & " + " & ".join(r"\texttt{" + tex(a) + "}" for a in archs) + r" \\"
        body = []
        for i, n in enumerate(sizes):
            body.append(fmt(n) + " & " + " & ".join(
                val(f"sweep {key} {n} {a}", g(sw, key, i, j), sf) for j, a in enumerate(archs)) + r" \\")
        write(fname, "\n".join([r"\begin{tabular}{@{}l" + "r" * len(archs) + "@{}}", r"\toprule",
                                r"\multicolumn{" + str(len(archs) + 1) + "}{c}{" + title + r"} \\",
                                r"\midrule", hdr, r"\midrule", *body, r"\bottomrule", r"\end{tabular}"]))

    # ---------- outside ----------
    od = load(os.path.join(RES, "outside.json"))
    to_ = trajs.get(prim_name + "_outside") or {}
    of = "standin" if fk_standin or nonreal(g(od, "model_source")) else None
    fr = g(od, "frac_outside")
    macro("OutName", "outside trajectory", g(od, "name") or (prim_name + "_outside"))
    macro("OutFracPct", "frac_outside", fr * 100 if num(fr) else None, of, digits=0)
    macro("OutErrIn", "err_inside_rms", g(od, "err_inside_rms_mm"), of)
    macro("OutErrOut", "err_outside_rms", g(od, "err_outside_rms_mm"), of)
    macro("OutErrOutMax", "err_outside_max", g(od, "err_outside_max_mm"), of)
    macro("OutResidMax", "nn_residual_max", g(od, "nn_residual_max_mm"), of)
    ov, oe = g(od, "err_vs_overshoot", "overshoot_deg"), g(od, "err_vs_overshoot", "err_mm")
    macro("OutMaxOvershoot", "max overshoot", max(ov) if ov else None, of, digits=1)
    macro("OutErrAtMaxOvershoot", "err at max overshoot",
          oe[ov.index(max(ov))] if ov and oe and len(oe) == len(ov) else None, of)
    r1 = g(od, "theta1_range_deg") or ([g(to_, "theta_min_deg", 0), g(to_, "theta_max_deg", 0)])
    macro("OutThOneMin", "outside theta1 min", g(r1, 0), of, digits=1)
    macro("OutThOneMax", "outside theta1 max", g(r1, 1), of, digits=1)
    macro("RegionThOneMax", "region theta1 max", g(cfg, "region", "theta1", 1))
    macro("OutWithinLimits", "outside within_limits", g(to_, "within_limits"), of)
    orob = g(to_, "robust_to_signs")
    if isinstance(orob, dict):
        okv = [v for v in orob.values() if isinstance(v, bool)]
        orob = all(okv) if okv else None
    macro("OutRobust", "outside robust_to_signs", orob, of)
    raw_macro("OutRobustOK", "1" if orob is True else "0")

    # ---------- run ----------
    rdirs = [RES_S] if SYNTH else [RES]
